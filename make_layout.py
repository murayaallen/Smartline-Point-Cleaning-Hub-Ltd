def img(label, cls=""):
    return '<div class="img %s"><span>%s</span></div>' % (cls, E(label))


def btns(labels):
    out = []
    for i, b in enumerate(labels):
        out.append('<span class="btn %s">%s</span>' % ("primary" if i == 0 else "ghost", E(b)))
    return '<div class="btns">%s</div>' % "".join(out)


