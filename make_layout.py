def build():
    n = verify()
    md = build_md(n)
    with open("LAYOUT.md", "w", encoding="utf-8") as f:
        f.write(md)
    page = build_html(n)
    with open("wireframes.html", "w", encoding="utf-8") as f:
        f.write(page)
    # post-build checks on the rendered output, not just the data
    # the eight page wireframes are the public site; the overview's planning note is allowed to name it
    for pg in L.PAGES:
        art = page_article(pg, key_for(pg)).lower()
        assert "fumigat" not in art, "fumigation leaked into the %s wireframe" % pg["slug"]
        assert ('data-page="%s"' % key_for(pg)) in page, "missing page " + pg["slug"]
    assert "fumigat" not in global_article().lower(), "fumigation leaked into the global chrome"
    for pg in L.PAGES + L.UTILITY_PAGES:
        art = page_article(pg, key_for(pg))
        for ph in ("Short line on the service", "Two lines on what"):
            assert ph not in art, "placeholder left on %s: %s" % (pg["slug"], ph)
        assert ('data-page="%s"' % key_for(pg)) in page, "missing page " + pg["slug"]
    assert len(re.findall(r'<section class="wf', page)) >= sum(len(p["sections"]) for p in L.PAGES)
    n_sec = sum(len(p["sections"]) for p in L.PAGES)
    print("verify OK: 8 pages, %d sections, %d global elements, %d services, %d contrast pairs pass" %
          (n_sec, len(L.GLOBAL), n, len(L.CONTRAST_PAIRS)))
    print("wrote LAYOUT.md (%d lines) and wireframes.html (%d KB)" %
          (md.count("\n"), len(page.encode("utf-8")) // 1024))


if __name__ == "__main__":
    build()
