def _lum(hexc):
    hexc = hexc.lstrip("#")
    rgb = [int(hexc[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    lin = [v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4 for v in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    la, lb = _lum(a), _lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def all_sections():
    for pg in L.PAGES:
        for s in pg["sections"]:
            yield pg, s


def verify():
    errs = []
    if len(L.PAGES) != 8:
        errs.append("expected 8 content pages, found %d" % len(L.PAGES))
    n_services = sum(len(items) for _, _, items in L.GROUPS)
    if n_services != 13:
        errs.append("expected 13 services, found %d" % n_services)
    ids = [s["id"] for _, s in all_sections()] + [g["id"] for g in L.GLOBAL]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        errs.append("duplicate section ids: %s" % dup)
    for pg in L.PAGES:
        if len(pg["title"]) > 60:
            errs.append("title over 60 chars (%d): %s" % (len(pg["title"]), pg["title"]))
        if not 110 <= len(pg["desc"]) <= 160:
            errs.append("description %d chars (want 110-160): %s" % (len(pg["desc"]), pg["slug"]))
    for fg, bg, use, need in L.CONTRAST_PAIRS:
        r = contrast(fg, bg)
        if r < need:
            errs.append("contrast %.2f < %.1f for %s (%s on %s)" % (r, need, use, fg, bg))
    for _, _, items in L.GROUPS:
        for name, _ in items:
            if name not in L.SERVICE_COPY:
                errs.append("no copy for service: %s" % name)
                continue
            desc, incl, who = L.SERVICE_COPY[name]
            if len(desc) > 110:
                errs.append("service line over 110 chars (%d): %s" % (len(desc), name))
            if len(incl) != 3:
                errs.append("service needs exactly 3 inclusions: %s" % name)
    for pg in L.PAGES:
        if not any(sec["type"] in ("cta", "form", "quickquote") for sec in pg["sections"]):
            errs.append("page has no conversion section: %s" % pg["slug"])
    for pg in L.UTILITY_PAGES:
        if len(pg["title"]) > 60:
            errs.append("utility title over 60 chars: %s" % pg["title"])
    uids = [sec["id"] for pg in L.UTILITY_PAGES for sec in pg["sections"]]
    if set(uids) & set(ids):
        errs.append("utility ids collide with page ids")
    blob = json.dumps([L.PAGES, L.GLOBAL, L.GROUPS, L.SERVICE_COPY, L.UTILITY_PAGES],
                      ensure_ascii=False).lower()
    if "fumigat" in blob:
        errs.append("fumigation appears in site content \u2014 it must stay off until licensed")
    if errs:
        raise SystemExit("verify() FAILED:\n  - " + "\n  - ".join(errs))
    return n_services


